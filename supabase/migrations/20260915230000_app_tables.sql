create or replace function public.disable_user(target_user_id uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if not public.is_admin() then
    raise exception 'Only an administrator can disable users';
  end if;

  if target_user_id = (select auth.uid()) then
    raise exception 'An administrator cannot disable their own account';
  end if;

  update public.profiles
  set is_disabled = true
  where id = target_user_id;
end;
$$;

revoke all on function public.disable_user(uuid) from public;
grant execute on function public.disable_user(uuid) to authenticated;

